import { readFileSync, writeFileSync } from "node:fs";
import { initializeApp, cert } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { getStorage } from "firebase-admin/storage";
import assert from "node:assert/strict";
const fixture = JSON.parse(readFileSync("output/host-qa/run.json", "utf8"));
if (!fixture.email.startsWith("guestsetgo-qa-") || !fixture.uid || !fixture.propertyId) throw new Error("A verified disposable QA host is required.");
const app = initializeApp({ credential: cert({ projectId: process.env.FIREBASE_PROJECT_ID, clientEmail: process.env.FIREBASE_CLIENT_EMAIL, privateKey: process.env.FIREBASE_PRIVATE_KEY.replace(/\\n/g,"\n") }) });
const db = getFirestore(app);
const account = (await db.collection("users").doc(fixture.uid).get()).data();
assert.equal(account.email, fixture.email);
const propertyRef = db.collection("properties").doc(fixture.propertyId);
const property = (await propertyRef.get()).data();
assert.equal(property.ownerUid, fixture.uid);
const request = (await propertyRef.collection("imports").doc("assisted").get()).data();
assert.equal(property.wifiName, "HarbourGuest");
assert.equal(property.published, false);
assert.equal(request.status, "submitted");
const bucket = getStorage(app).bucket(process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET);
const file = bucket.file(request.paths[0]);
assert.equal((await file.exists())[0], true);
const [metadata] = await file.getMetadata();
assert.equal(metadata.metadata?.firebaseStorageDownloadTokens, undefined);
const response = await fetch(`https://firebasestorage.googleapis.com/v0/b/${bucket.name}/o/${encodeURIComponent(request.paths[0])}?alt=media`);
assert.equal(response.status, 403);
const result = { importedWiFiSaved: true, propertyOffline: true, privateSourceExists: true, publicReadDenied: true, noPublicDownloadToken: true, hostingPlan: account.plan || null, subscriptionStatus: account.subscriptionStatus || null };
fixture.results["private-state"] = result;
writeFileSync("output/host-qa/run.json", JSON.stringify(fixture));
console.log(JSON.stringify(result));
